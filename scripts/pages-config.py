#!/usr/bin/env python3
"""Build .pages.yml (Pages CMS) from scripts/pages.base.yml, once per language.

Every collection/file in the base config is repeated for each language:
  path content/stories        -> content/nl/stories, content/en/stories
  name stories                -> stories_nl, stories_en
  reference collection: trails -> trails_nl / trails_en
Run from the repo root:  python3 scripts/pages-config.py
Needs PyYAML (pip install pyyaml).
"""
import copy
import os
import yaml

LANGS = [("nl", "Nederlands"), ("en", "English")]
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)

base = yaml.safe_load(open(os.path.join(HERE, "pages.base.yml")))
names = set()


def collect_names(items):
    for it in items:
        if it.get("type") == "group":
            collect_names(it["items"])
        else:
            names.add(it["name"])


collect_names(base["content"])


def fix_fields(fields, lang):
    for f in fields or []:
        opts = f.get("options") or {}
        if f.get("type") == "reference" and opts.get("collection") in names:
            opts["collection"] = f'{opts["collection"]}_{lang}'
        if f.get("fields"):
            fix_fields(f["fields"], lang)


def localise(item, lang, label):
    it = copy.deepcopy(item)
    if it.get("type") == "group":
        it["name"] = f'{it["name"]}_{lang}'
        it["items"] = [localise(x, lang, label) for x in it["items"]]
        return it
    it["name"] = f'{it["name"]}_{lang}'
    it["path"] = it["path"].replace("content/", f"content/{lang}/", 1)
    fix_fields(it.get("fields"), lang)
    return it


out = {"media": base["media"], "content": []}
for lang, label in LANGS:
    out["content"].append({
        "name": lang,
        "label": label,
        "type": "group",
        # one group per language; nested groups (the base "Pages" group) are flattened into it
        "items": [localise(y, lang, label) for x in base["content"] for y in (x["items"] if x.get("type") == "group" else [x])],
    })

header = (
    "# GENERATED by scripts/pages-config.py from scripts/pages.base.yml — edit the base file, not this one.\n"
    "# Pages CMS configuration for patrickontrack.nl (Hugo). Docs: https://pagescms.org/docs/configuration/\n"
    "# One set of collections per language: Nederlands (content/nl) and English (content/en).\n"
    "# A page that exists in only one language is shown on the other language's site too, with a note.\n\n"
)
with open(os.path.join(ROOT, ".pages.yml"), "w") as f:
    f.write(header + yaml.safe_dump(out, sort_keys=False, allow_unicode=True, width=200))
print("wrote .pages.yml")
